-- Run in the Supabase SQL Editor before supabase_policies.sql.
-- Public visitors may read surveys and vote, but only the FastAPI admin API
-- (using a private Supabase secret key) may create or activate surveys.

create extension if not exists pgcrypto;

create table if not exists public.surveys (
  id uuid primary key default gen_random_uuid(),
  title text not null check (char_length(trim(title)) between 1 and 80),
  question text not null check (char_length(trim(question)) between 1 and 180),
  instruction text not null check (char_length(trim(instruction)) between 1 and 120),
  choice_heading text not null default 'VOTRE CHOIX'
    check (char_length(trim(choice_heading)) between 1 and 120),
  is_active boolean not null default false,
  created_at timestamptz not null default now()
);

create table if not exists public.survey_choices (
  id bigint generated by default as identity primary key,
  survey_id uuid not null references public.surveys(id) on delete cascade,
  label text not null check (char_length(trim(label)) between 1 and 80),
  description text not null default ''
    check (char_length(description) <= 120),
  mark text not null default '✳' check (char_length(mark) between 1 and 8),
  sort_order smallint not null,
  unique (survey_id, label),
  unique (survey_id, sort_order)
);

alter table public.votes
  add column if not exists survey_id uuid;

do $$
begin
  if not exists (
    select 1
    from pg_constraint
    where conname = 'votes_survey_id_fkey'
      and conrelid = 'public.votes'::regclass
  ) then
    alter table public.votes
      add constraint votes_survey_id_fkey
      foreign key (survey_id) references public.surveys(id);
  end if;
end;
$$;

create unique index if not exists surveys_single_active_idx
  on public.surveys (is_active)
  where is_active;

alter table public.surveys enable row level security;
alter table public.survey_choices enable row level security;

grant select on public.surveys, public.survey_choices to anon;

drop policy if exists survey_public_read_surveys on public.surveys;
create policy survey_public_read_surveys
  on public.surveys for select to anon
  using (true);

drop policy if exists survey_public_read_choices on public.survey_choices;
create policy survey_public_read_choices
  on public.survey_choices for select to anon
  using (true);

insert into public.surveys (title, question, instruction, choice_heading, is_active)
select
  'TA VOIX',
  'Comment as-tu vécu cette séance ?',
  'Choisis le ressenti qui te correspond le mieux.',
  'TON RESSENTI',
  true
where not exists (select 1 from public.surveys);

insert into public.survey_choices (survey_id, label, description, mark, sort_order)
select initial_survey.id, choice.label, choice.description, choice.mark, choice.sort_order
from (
  select id from public.surveys order by created_at asc limit 1
) as initial_survey
cross join (
  values
    ('Très bien', 'Au-dessus des attentes', '↗', 1),
    ('Bien', 'Une bonne expérience', '✳', 2),
    ('Moyen', 'Peut mieux faire', '◌', 3),
    ('À revoir', 'À retravailler ensemble', '↻', 4)
) as choice(label, description, mark, sort_order)
where not exists (
  select 1
  from public.survey_choices existing_choice
  where existing_choice.survey_id = initial_survey.id
);

update public.votes
set survey_id = (
  select id from public.surveys order by created_at asc limit 1
)
where survey_id is null;

alter table public.votes
  alter column survey_id set not null;

create or replace function public.create_survey(survey_data jsonb)
returns uuid
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  new_survey_id uuid;
  survey_choice jsonb;
  choice_index integer := 0;
  choice_count integer;
begin
  if char_length(trim(coalesce(survey_data->>'title', ''))) not between 1 and 80
    or char_length(trim(coalesce(survey_data->>'question', ''))) not between 1 and 180
    or char_length(trim(coalesce(survey_data->>'instruction', ''))) not between 1 and 120
    or char_length(trim(coalesce(survey_data->>'choice_heading', ''))) not between 1 and 120
  then
    raise exception 'Survey text fields are invalid';
  end if;

  if coalesce(jsonb_typeof(survey_data->'choices') <> 'array', true) then
    raise exception 'choices must be an array';
  end if;

  choice_count := jsonb_array_length(survey_data->'choices');
  if choice_count < 2 or choice_count > 8 then
    raise exception 'A survey must have between 2 and 8 choices';
  end if;

  update public.surveys set is_active = false where is_active;

  insert into public.surveys (
    title, question, instruction, choice_heading, is_active
  )
  values (
    survey_data->>'title',
    survey_data->>'question',
    survey_data->>'instruction',
    survey_data->>'choice_heading',
    true
  )
  returning id into new_survey_id;

  for survey_choice in
    select value from jsonb_array_elements(survey_data->'choices')
  loop
    insert into public.survey_choices (
      survey_id, label, description, mark, sort_order
    )
    values (
      new_survey_id,
      survey_choice->>'label',
      coalesce(survey_choice->>'description', ''),
      coalesce(survey_choice->>'mark', '✳'),
      choice_index
    );
    choice_index := choice_index + 1;
  end loop;

  return new_survey_id;
end;
$$;

revoke all on function public.create_survey(jsonb) from public, anon, authenticated;
grant execute on function public.create_survey(jsonb) to service_role;
